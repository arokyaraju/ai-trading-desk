import datetime
from typing import Optional
from sqlalchemy import (
    Column, Integer, String, Float, Boolean, DateTime, Text, ForeignKey, JSON, Index
)
from sqlalchemy.orm import declarative_base, relationship

Base = declarative_base()

class MarketBar(Base):
    """OHLCV candlestick bars stored by symbol and timeframe."""
    __tablename__ = "market_bars"

    id = Column(Integer, primary_key=True, autoincrement=True)
    symbol = Column(String(50), nullable=False, index=True)
    timeframe = Column(String(10), nullable=False, default="5m")  # 1m, 5m, 15m, 1h, 1d
    timestamp = Column(DateTime, nullable=False, index=True)
    open = Column(Float, nullable=False)
    high = Column(Float, nullable=False)
    low = Column(Float, nullable=False)
    close = Column(Float, nullable=False)
    volume = Column(Float, nullable=False, default=0.0)
    oi = Column(Float, nullable=True)

    __table_args__ = (
        Index("idx_sym_tf_time", "symbol", "timeframe", "timestamp", unique=True),
    )


class SectorSnapshot(Base):
    """Sector index performance, intraday change, and rank over time."""
    __tablename__ = "sector_snapshots"

    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(DateTime, default=datetime.datetime.utcnow, index=True)
    sector_name = Column(String(100), nullable=False, index=True)
    symbol = Column(String(50), nullable=False)
    price = Column(Float, nullable=False)
    change_pct = Column(Float, nullable=False)
    momentum_score = Column(Float, default=0.0)
    advances = Column(Integer, default=0)
    declines = Column(Integer, default=0)
    rank = Column(Integer, nullable=False)
    status = Column(String(20), default="ACTIVE")  # LEADING, LAGGING, REVERSING


class MarketRegime(Base):
    """Nifty regime classification, pivot/close interactions, opening range."""
    __tablename__ = "market_regimes"

    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(DateTime, default=datetime.datetime.utcnow, index=True)
    index_symbol = Column(String(50), default="NSE:NIFTY50-INDEX")
    current_price = Column(Float, nullable=False)
    prev_close = Column(Float, nullable=False)
    daily_pivot = Column(Float, nullable=False)
    opening_range_high = Column(Float, nullable=True)
    opening_range_low = Column(Float, nullable=True)
    first_15m_breakout = Column(String(20), default="NONE")  # BULLISH_BREAKOUT, BEARISH_BREAKDOWN, INSIDE
    bias = Column(String(20), nullable=False)  # BULLISH, BEARISH, NEUTRAL
    rationale = Column(Text, nullable=True)


class AgentSignal(Base):
    """Signals generated by Agents #1 to #7."""
    __tablename__ = "agent_signals"

    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(DateTime, default=datetime.datetime.utcnow, index=True)
    agent_id = Column(String(50), nullable=False, index=True)  # e.g. "Agent 1 — Sector Radar"
    rule_version = Column(String(20), default="v1.0")
    symbol = Column(String(50), nullable=False, index=True)
    direction = Column(String(10), nullable=False)  # BUY, SELL, NEUTRAL
    signal_type = Column(String(50), nullable=False) # PWH_REJECTION, PDL_RECOVERY, etc.
    timeframe = Column(String(10), default="1h")
    reference_price = Column(Float, nullable=False)
    trigger_price = Column(Float, nullable=False)
    reason = Column(Text, nullable=False)
    metadata_json = Column(JSON, nullable=True)


class TradeCandidate(Base):
    """Manager's evaluated and scored candidates."""
    __tablename__ = "trade_candidates"

    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(DateTime, default=datetime.datetime.utcnow, index=True)
    symbol = Column(String(50), nullable=False, index=True)
    direction = Column(String(10), nullable=False)
    setup_name = Column(String(100), nullable=False)
    discovering_agent = Column(String(50), nullable=False)
    
    # 5 Scoring Factors
    nifty_score = Column(Float, default=0.0)      # 25% weight
    sector_score = Column(Float, default=0.0)     # 20% weight
    stock_conf_score = Column(Float, default=0.0) # 20% weight
    level_setup_score = Column(Float, default=0.0)# 20% weight
    risk_reward_score = Column(Float, default=0.0)# 15% weight
    composite_score = Column(Float, default=0.0)  # Total 0-100
    
    status = Column(String(30), default="PENDING") # CONFIRMED, REJECTED, WATCHING
    rejection_reason = Column(Text, nullable=True)
    disagreement_explanation = Column(Text, nullable=True)
    details = Column(JSON, nullable=True)


class TradePlan(Base):
    """Risk-managed actionable trade plans produced by Manager + Risk Officer."""
    __tablename__ = "trade_plans"

    id = Column(Integer, primary_key=True, autoincrement=True)
    plan_id = Column(String(100), unique=True, nullable=False, index=True)
    timestamp = Column(DateTime, default=datetime.datetime.utcnow, index=True)
    symbol = Column(String(50), nullable=False, index=True)
    direction = Column(String(10), nullable=False)
    setup_rationale = Column(Text, nullable=False)
    
    entry_price = Column(Float, nullable=False)
    initial_stop_loss = Column(Float, nullable=False)
    current_stop_loss = Column(Float, nullable=False)
    stop_distance = Column(Float, nullable=False)  # R
    planned_quantity = Column(Integer, nullable=False)
    risk_budget_inr = Column(Float, nullable=False)
    
    # Target Ladder 1R to 6R
    target_1r = Column(Float, nullable=False)
    target_2r = Column(Float, nullable=False)
    target_3r = Column(Float, nullable=False)
    target_4r = Column(Float, nullable=False)
    target_5r = Column(Float, nullable=False)
    target_6r = Column(Float, nullable=False)
    
    # State tracking: PAPER or PENDING_REAL
    mode = Column(String(20), default="PAPER")  # PAPER, REAL
    status = Column(String(30), default="OPEN") # OPEN, ACTIVE, CLOSED, CANCELLED
    trailing_milestone = Column(String(20), default="0R") # 0R, +1R, +2R (BE), +3R, etc.
    pnl_realized_inr = Column(Float, default=0.0)
    pnl_r_multiple = Column(Float, default=0.0)


class TradeEvent(Base):
    """Audit trail of trade updates: Entry, Stop Changes, Target Hits, Exits."""
    __tablename__ = "trade_events"

    id = Column(Integer, primary_key=True, autoincrement=True)
    timestamp = Column(DateTime, default=datetime.datetime.utcnow, index=True)
    plan_id = Column(String(100), nullable=False, index=True)
    event_type = Column(String(50), nullable=False) # ENTRY, STOP_ADJUSTMENT, TARGET_TOUCH, EXIT, MANUAL_OVERRIDE
    price = Column(Float, nullable=False)
    details = Column(Text, nullable=False)


class RealTrade(Base):
    """Manually recorded real trades executed by the user with actual broker fills."""
    __tablename__ = "real_trades"

    id = Column(Integer, primary_key=True, autoincrement=True)
    trade_id = Column(String(100), unique=True, nullable=False, index=True)
    plan_id = Column(String(100), nullable=True) # Linked trade plan if any
    symbol = Column(String(50), nullable=False, index=True)
    direction = Column(String(10), nullable=False)
    entry_time = Column(DateTime, default=datetime.datetime.utcnow)
    entry_price = Column(Float, nullable=False)
    quantity = Column(Integer, nullable=False)
    broker_order_id = Column(String(100), nullable=True)
    
    initial_sl = Column(Float, nullable=False)
    current_sl = Column(Float, nullable=False)
    exit_time = Column(DateTime, nullable=True)
    exit_price = Column(Float, nullable=True)
    
    slippage = Column(Float, default=0.0)
    brokerage_and_taxes = Column(Float, default=20.0) # standard estimate
    net_pnl = Column(Float, default=0.0)
    r_multiple = Column(Float, default=0.0)
    status = Column(String(20), default="OPEN") # OPEN, CLOSED
    notes = Column(Text, nullable=True)


class DailyJournal(Base):
    """End-of-day permanent trading memory and narrative."""
    __tablename__ = "daily_journal"

    id = Column(Integer, primary_key=True, autoincrement=True)
    date_str = Column(String(20), unique=True, nullable=False, index=True) # YYYY-MM-DD
    timestamp = Column(DateTime, default=datetime.datetime.utcnow)
    nifty_opening = Column(Float, nullable=True)
    nifty_prev_close = Column(Float, nullable=True)
    nifty_pivot = Column(Float, nullable=True)
    top_sector_1 = Column(String(50), nullable=True)
    top_sector_2 = Column(String(50), nullable=True)
    total_candidates_scored = Column(Integer, default=0)
    total_trades_taken = Column(Integer, default=0)
    win_count = Column(Integer, default=0)
    loss_count = Column(Integer, default=0)
    net_pnl_inr = Column(Float, default=0.0)
    narrative_summary = Column(Text, nullable=True)
    report_json = Column(JSON, nullable=True)


